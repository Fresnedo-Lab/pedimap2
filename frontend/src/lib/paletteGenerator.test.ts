// Writes palettes.ts. Runs only when asked (it takes about two minutes):
//   GENERATE_PALETTES=1 npx vitest run src/lib/paletteGenerator.test.ts
import { describe, it } from "vitest";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { generateAlleleColors, generateFounderPairs } from "./paletteGenerator";

export const FOUNDERS = 30;
export const ALLELES = 60;

describe.skipIf(!process.env.GENERATE_PALETTES)("palette generator", () => {
  it("writes palettes.ts", () => {
    const small = generateFounderPairs(FOUNDERS);
    const large = generateFounderPairs(FOUNDERS, 3);
    const alleles = generateAlleleColors(ALLELES);
    const list = (xs: unknown[]) => xs.map(x => `  ${JSON.stringify(x)},`).join("\n");
    writeFileSync(resolve("src/lib/palettes.ts"), `// lib/palettes.ts
// ===============
// Generated by paletteGenerator.ts; do not edit. Regenerate with
//   GENERATE_PALETTES=1 npx vitest run src/lib/paletteGenerator.test.ts

/** Founder shades (light, dark), greedy: the first few the most separated.
 *  For up to SMALL_PALETTE_FOUNDERS contributing founders. */
export const FOUNDER_PAIRS_SMALL: [string, string][] = [
${list(small)}
];

/** Founder shades refined for many founders at once (more contributing
 *  founders than SMALL_PALETTE_FOUNDERS). */
export const FOUNDER_PAIRS_LARGE: [string, string][] = [
${list(large)}
];

/** One color per founder allele, greedy. */
export const ALLELE_COLORS: string[] = [
${list(alleles)}
];
`);
  }, 900_000);
});
